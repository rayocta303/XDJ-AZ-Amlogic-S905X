def send_overlay(bus_id, frame):
    s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    s.sendto(bytes([bus_id]) + bytes(frame), ('127.0.0.1', 9999))
    s.close()

def clear_overlay(bus_id):
    s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    s.sendto(bytes([bus_id]), ('127.0.0.1', 9999))
    s.close()

def press_mixer_btn(tab_mask=0, corner_mask=0, hold=0.2):
    f = bytearray(AZ_IDLE_MIXER)
    f[6] = 0x00 # Latch pressed
    f[32] = tab_mask & 0xFF
    f[33] = corner_mask & 0xFF
    send_overlay(2, f)
    time.sleep(hold)
    clear_overlay(2)

